// Empacota tudo em um HTML local. Uso na produção: node prototipo-mapa/gerar.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(base,'..');
const three=await fs.readFile(path.join(root,'fontes/vendor/three.module.js'),'utf8');
const license=await fs.readFile(path.join(root,'fontes/vendor/LICENCA-THREE.txt'),'utf8');
// A versão fixada 0.170.0 é um módulo único, sem importações externas.
const exportMatch=three.match(/export \{ ([^}]+) \};\s*$/);
if(!exportMatch)throw new Error('Formato da biblioteca diferente do esperado');
const bundled=three.replace(exportMatch[0],`const T = { ${exportMatch[1]} };`);
const car=(await fs.readFile(path.join(root,'modelos/carro.glb'))).toString('base64');
let svg=await fs.readFile(path.join(root,'midias/mahle-azul.svg'),'utf8');
svg=svg.slice(svg.indexOf('<svg')).replace('<svg','<svg class="brand" role="img" aria-label="MAHLE"');
const damage=await fs.readFile(path.join(base,'dano.js'),'utf8');
const vegetation=await fs.readFile(path.join(base,'vegetacao.js'),'utf8');
const manifold=await fs.readFile(path.join(base,'coletor.js'),'utf8');
const viewer=await fs.readFile(path.join(base,'visor-coletor.js'),'utf8');
const visibility=await fs.readFile(path.join(base,'visibilidade-mapa.js'),'utf8');
const effects=await fs.readFile(path.join(base,'efeitos-coletor.js'),'utf8');
const demos=await fs.readFile(path.join(base,'demonstracoes.js'),'utf8');
const productScenes=await fs.readFile(path.join(base,'cenas-produto.js'),'utf8');
const serviceScene=await fs.readFile(path.join(base,'cena-servico.js'),'utf8');
const corrosionScene=await fs.readFile(path.join(base,'cena-corrosao.js'),'utf8');
const airScene=await fs.readFile(path.join(base,'cena-distribuicao.js'),'utf8');
const backfireScene=await fs.readFile(path.join(base,'cena-backfire.js'),'utf8');
const waterScene=await fs.readFile(path.join(base,'cena-agua.js'),'utf8');
const css=await fs.readFile(path.join(base,'apresentacao.css'),'utf8');
const config=JSON.parse(await fs.readFile(path.join(base,'configuracao.json'),'utf8'));
config.slides=JSON.parse(await fs.readFile(path.join(base,'slides.json'),'utf8'));
config.codigoRastreabilidade=JSON.parse(await fs.readFile(path.join(base,'codigo-rastreabilidade.json'),'utf8'));
let app=(await fs.readFile(path.join(base,'movimento.js'),'utf8')).replace('__CARRO_BASE64__',car).replace('__DANO_SOURCE__',()=>damage).replace('__VEGETACAO_SOURCE__',()=>vegetation).replace('__COLETOR_SOURCE__',()=>manifold).replace('__VISOR_SOURCE__',()=>viewer).replace('__DEMOS_SOURCE__',()=>demos).replace('__CENAS_PRODUTO_SOURCE__',()=>productScenes).replace('__CENA_SERVICO_SOURCE__',()=>serviceScene).replace('__VISIBILITY_SOURCE__',()=>visibility).replace('__EFFECTS_SOURCE__',()=>effects).replace('__CONFIG_SOURCE__',()=>`const CONFIG=${JSON.stringify(config)};const STOP_COUNT=CONFIG.paradas.length,LAST_STOP=STOP_COUNT-1,FINAL_SLIDE=STOP_COUNT,STOP_PARAMS=CONFIG.paradas.map(p=>p.u);`);
const labels=config.slides.map((s,i)=>{const same=config.slides.filter(p=>p.severidade===s.severidade);return same.length>1?s.severidade+'·'+(same.indexOf(s)+1):String(s.severidade).padStart(2,'0')}).concat('Fim');
app=app.replace('__CENA_CORROSAO_SOURCE__',()=>corrosionScene);
app=app.replace('__CENA_DISTRIBUICAO_SOURCE__',()=>airScene);
app=app.replace('__CENA_AGUA_SOURCE__',()=>waterScene);
app=app.replace('__CENA_BACKFIRE_SOURCE__',()=>backfireScene);
const steps=labels.map((label,i)=>`<button class="step" id="etapa-${i}" aria-label="${i===config.slides.length?'Selecionar conclusão':'Selecionar severidade '+config.slides[i].severidade+': '+config.slides[i].titulo}" type="button">${label}</button>`).join('');
let html=await fs.readFile(path.join(base,'interface.html'),'utf8');
const p=config.painel,panelCSS=`--painel-x:${p.margemLateral*100}%;--painel-y:${p.topo*100}%;--painel-largura:${p.largura*100}%;--painel-altura:${p.altura*100}%;--painel-opacidade:${p.opacidade};`;
html=html.replace('__PAINEL_CSS__',panelCSS).replace('__LOGO__',svg).replace('__ETAPAS__',steps).replace('__THREE__',()=>bundled).replace('__APP__',()=>app).replace('__APRESENTACAO_CSS__',()=>css);
html=html.replace('<html lang="pt-BR">',()=>`<!-- Licença da biblioteca incorporada:\n${license}\n-->\n<html lang="pt-BR">`);
await fs.writeFile(path.join(base,'iniciar.html'),html);
console.log('Arquivo offline gerado:',path.join(base,'iniciar.html'));
